#!/usr/bin/env python3
"""Compiles the compositor's shaders and writes userland/desktop/wayland/shaders.h.

The build uses the checked-in header, so no shader compiler is needed to
build the compositor; run this (with glslc and spirv-val on PATH) after changing a
shader.
Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
"""
import pathlib
import struct
import subprocess
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SHADERS = [("quad.vert", "kwl_quad_vert"), ("quad.frag", "kwl_quad_frag"),
           ("panel.vert", "kwl_panel_vert"), ("panel.frag", "kwl_panel_frag"),
           ("panel-batch.vert", "kwl_batch_vert"), ("panel-batch.frag", "kwl_batch_frag"),
           ("turn.vert", "kwl_turn_vert")]


def compile_shader(source, definitions=()):
    """Returns the validated SPIR-V words of one shader."""
    with tempfile.TemporaryDirectory() as directory:
        output = pathlib.Path(directory) / "shader.spv"
        subprocess.run(["glslc", "--target-env=vulkan1.0", "-O", *definitions, str(source),
                        "-o", str(output)], check=True, timeout=30)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.0",
                        str(output)], check=True, timeout=30)
        data = output.read_bytes()
    return struct.unpack("<%dI" % (len(data) // 4), data)


def main():
    lines = ["/*", " * zedBSD", " * Copyright (C) 2026 Awe Morris", " *",
             " * SPDX-License-Identifier: Zlib", " */", "",
             "/* Generated by shaders/regenerate.py from the shaders in shaders/; do not edit. */",
             "", "#ifndef KWL_SHADERS_H", "#define KWL_SHADERS_H", "",
             "#include <stdint.h>", "",
             "/* One immutable panel mode retains its exact SPIR-V word extent. */",
             "struct kwl_panel_shader {", "\tconst uint32_t *words;",
             "\tuint32_t bytes;", "};", ""]
    variants = [(source, name, ()) for source, name in SHADERS]
    variants.extend(("panel.frag", "kwl_panel_frag_%d" % mode,
                     ("-DKWL_PANEL_MODE=%d" % mode,)) for mode in range(8))
    for source, name, definitions in variants:
        words = compile_shader(HERE / source, definitions)
        lines.append("/* Validated immutable %s SPIR-V, used while creating graphics pipelines. */" % name)
        lines.append("static const uint32_t %s[] = {" % name)
        for index in range(0, len(words), 6):
            chunk = ", ".join("0x%08xU" % word for word in words[index:index + 6])
            lines.append("\t%s," % chunk)
        lines.append("};")
        lines.append("")
    lines.extend(["/* Glass, shadow, image, solid, ring, text, blur and dark glass avoid unused branch work. */",
                  "static const struct kwl_panel_shader kwl_panel_variants[8] = {"])
    for mode in range(8):
        lines.append("\t{kwl_panel_frag_%d, sizeof(kwl_panel_frag_%d)}," % (mode, mode))
    lines.extend(["};", "", "#endif"])
    (HERE.parent / "shaders.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
