#!/usr/bin/env python3
"""Compiles vkmatrix's shaders and writes userland/tests/vkmatrix/shader.h.

The build uses the checked-in header, so no shader compiler is needed;
run this (with glslc and spirv-val on PATH) after changing a shader.
Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
"""
import pathlib
import struct
import subprocess
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SHADERS = ["push4.vert", "push4.frag", "push32.vert", "push32.frag", "push128.vert", "push128.frag",
           "batch.vert", "batch.frag", "texture.vert", "texture.frag", "immediate.frag", "alu.frag", "alu4.frag", "mul4.frag", "rcp.frag",
           "uniform.vert", "uniform.frag", "alupix.frag", "alusq.frag", "alusq32.frag", "flatblend.frag",
           "sopr000.frag", "sop0g00.frag", "sop00b0.frag", "sop000a.frag", "soprrrr.frag", "sopabgr.frag", "sopr111.frag",
           "sopinv.frag", "sophalf.frag", "sopsq.frag", "sopta.frag", "sopmad.frag", "sopxy01.frag"]


def compile_shader(source):
    """Returns the validated SPIR-V words of one shader."""
    with tempfile.TemporaryDirectory() as directory:
        output = pathlib.Path(directory) / "shader.spv"
        subprocess.run(["glslc", "--target-env=vulkan1.0", str(source), "-o", str(output)], check=True, timeout=30)
        subprocess.run(["spirv-val", "--target-env", "vulkan1.0", str(output)], check=True, timeout=30)
        data = output.read_bytes()
    return struct.unpack("<%dI" % (len(data) // 4), data)


def main():
    lines = ["/*", " * zedBSD", " * Copyright (C) 2026 Awe Morris", " *",
             " * SPDX-License-Identifier: Zlib", " */", "",
             "/* Generated by shaders/regenerate.py from the shaders in shaders/; do not edit. */",
             "", "#ifndef VKMATRIX_SHADER_H", "#define VKMATRIX_SHADER_H", "",
             "#include <stdint.h>", ""]
    for name in SHADERS:
        words = compile_shader(HERE / name)
        symbol = "vkmatrix_" + name.replace(".", "_")
        lines.append("static const uint32_t %s[] = {" % symbol)
        for at in range(0, len(words), 4):
            lines.append("\t" + " ".join("0x%08xU," % w for w in words[at:at + 4]))
        lines.append("};")
        lines.append("")
    lines.append("#endif /* VKMATRIX_SHADER_H */")
    (HERE.parent / "shader.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
