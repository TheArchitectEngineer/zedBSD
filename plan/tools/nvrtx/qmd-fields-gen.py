#!/usr/bin/env python3
# Writes plan/tools/nvrtx/qmd-fields.h: the bit positions of the QMD fields
# nvrtx writes (and the ones it must leave zero), read mechanically from
# NVIDIA open-gpu-doc's classes/compute/clc3c0qmd.h (V02_02, the QMD of Turing's class),
# clc7c0qmd.h (V03_00, Ampere) and clc9c0qmd.h (V03_00, Ada), so the host
# test's expectations are not copied by hand next to the driver's.
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
#
# usage: python3 -I plan/tools/nvrtx/qmd-fields-gen.py OPEN-GPU-DOC-DIR > plan/tools/nvrtx/qmd-fields.h
import hashlib
import os
import re
import subprocess
import sys

FIELDS = [
    "QMD_VERSION", "QMD_MAJOR_VERSION", "SM_GLOBAL_CACHING_ENABLE", "API_VISIBLE_CALL_LIMIT",
    "SAMPLER_INDEX", "CTA_RASTER_WIDTH", "CTA_RASTER_HEIGHT", "CTA_RASTER_DEPTH",
    "SHARED_MEMORY_SIZE", "MIN_SM_CONFIG_SHARED_MEM_SIZE", "MAX_SM_CONFIG_SHARED_MEM_SIZE",
    "TARGET_SM_CONFIG_SHARED_MEM_SIZE", "SHARED_ALLOCATION_ENABLE",
    "CTA_THREAD_DIMENSION0", "CTA_THREAD_DIMENSION1", "CTA_THREAD_DIMENSION2",
    "REGISTER_COUNT_V", "BARRIER_COUNT",
    "CONSTANT_BUFFER_VALID(i)", "CONSTANT_BUFFER_ADDR_LOWER(i)", "CONSTANT_BUFFER_ADDR_UPPER(i)",
    "CONSTANT_BUFFER_SIZE_SHIFTED4(i)", "PROGRAM_ADDRESS_LOWER", "PROGRAM_ADDRESS_UPPER",
]
VERSIONS = [
    ("QMD22_TURING", "clc3c0qmd.h", "NVC3C0_QMDV02_02_"),
    ("QMD30_AMPERE", "clc7c0qmd.h", "NVC7C0_QMDV03_00_"),
    ("QMD30_ADA", "clc9c0qmd.h", "NVC9C0_QMDV03_00_"),
]


BOUND = re.compile(r"^\(?(\d+)(?:\+\(i\)\*(\d+))?\)?$")


def bound(text):
    # One end of MW(high:low): a number, or (number+(i)*stride) for a field of constant buffer i.
    found = BOUND.match(text.strip())
    if found is None:
        raise SystemExit("unexpected field bound: " + text)
    return int(found.group(1)), int(found.group(2) or 0)


def positions(text, prefix, field):
    pattern = re.compile(r"#define\s+" + re.escape(prefix + field) + r"\s+MW\((.*)\)\s*$", re.M)
    found = pattern.search(text)
    if found is None:
        return None
    high, low = found.group(1).split(":")
    high, high_stride = bound(high)
    low, low_stride = bound(low)
    if high_stride != low_stride:
        raise SystemExit("uneven stride: " + field)
    return high, low, low_stride


def main():
    root = sys.argv[1]
    try:
        revision = subprocess.run(["git", "-C", root, "log", "-1", "--format=%H"], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        revision = "unknown"
    print("/*")
    print(" * Generated by plan/tools/nvrtx/qmd-fields-gen.py; do not edit.")
    print(" *")
    print(" * Values referenced: NVIDIA open-gpu-doc (MIT) revision " + revision)
    for name, file, prefix in VERSIONS:
        data = open(os.path.join(root, "classes", "compute", file), "rb").read()
        print(" * classes/compute/%s sha256 %s" % (file, hashlib.sha256(data).hexdigest()))
    print(" * (the MW(high:low) positions of the fields; a field of constant buffer i for i = 0, with its stride).")
    print(" */")
    print()
    print("struct qmd_field {")
    print("\tconst char *name;")
    print("\tint present;")
    print("\tunsigned high;")
    print("\tunsigned low;")
    print("\t/* The step of a constant buffer's field from one buffer to the next (0 for the others). */")
    print("\tunsigned stride;")
    print("};")
    print()
    print("enum qmd_field_index {")
    for field in FIELDS:
        print("\tQMD_F_%s," % field.replace("(i)", ""))
    print("\tQMD_F_COUNT")
    print("};")
    for name, file, prefix in VERSIONS:
        text = open(os.path.join(root, "classes", "compute", file), encoding="latin-1").read()
        print()
        print("static const struct qmd_field qmd_fields_%s[QMD_F_COUNT] = {" % name.lower())
        for field in FIELDS:
            place = positions(text, prefix, field)
            if place is None:
                print('\t{ "%s", 0, 0U, 0U, 0U },' % field)
            else:
                print('\t{ "%s", 1, %uU, %uU, %uU },' % (field, place[0], place[1], place[2]))
        print("};")


main()
