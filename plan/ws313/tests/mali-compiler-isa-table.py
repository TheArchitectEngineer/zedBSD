#!/usr/bin/env python3
"""Generates the Valhall instruction table of the Mali compiler's host decoder from Mesa's ISA description.

Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib

The table is data read from Mesa 26.2.6 (MIT) src/panfrost/compiler/bifrost/valhall/ISA.xml: for every
instruction, the opcode bits that identify it, its sources (and their modifier fields), its destination,
its staging registers and whether it is a message.  The decoder in tests/mali-compiler-host-test.c reads
the compiler's words through this table alone, so that a word the compiler's own encoder gets wrong does
not decode as what the compiler meant.  Nothing of Mesa's code is used.

usage: mali-compiler-isa-table.py ISA.xml OUT.inc        writes the C table
       mali-compiler-isa-table.py ISA.xml --enums        prints every enum with its values' encodings
"""
import sys
import xml.etree.ElementTree as ET


def typesize(name):
    """The operand size an instruction name implies (the last digits of its type suffix)."""
    if name.endswith("128"):
        return 128
    if name.endswith("48"):
        return 48
    if name.endswith("8"):
        return 8
    try:
        return int(name[-2:])
    except ValueError:
        return 32


def opcode_bits(element):
    """The identifying (mask, value) of an <opcode> element, as 64-bit integers."""
    mask = 0
    value = 0
    opcode = element.find("opcode")
    if opcode is None:
        return None
    for op in opcode:
        start = int(op.get("start"))
        mask |= int(op.get("mask"), 0) << start
        value |= int(op.get("val"), 0) << start
    return (mask, value)


def source_flags(src):
    """The modifier fields a source has, as bits of the table's flags."""
    flags = 0
    for bit, attribute in enumerate(["absneg", "swizzle", "widen", "lane", "not", "combine", "halfswizzle", "lanes"]):
        if src.get(attribute, "false") not in ("false", None):
            flags |= 1 << bit
    return flags


def entry(element, name, opcode, unit):
    """One table row for an instruction (or a member of a group)."""
    size = typesize(name)
    sources = []
    for src in element.findall("src"):
        if src.get("pseudo", "false") == "true":
            continue
        sources.append((source_flags(src), int(src.get("size", size))))
    sources += [(0, size)] * int(element.get("srcs", "0"))
    dests = len(element.findall("dest")) + int(element.get("dests", "0"))
    staging = element.findall("sr")
    sr_read = sum(1 for sr in staging if sr.get("read", "false") == "true")
    sr_write = sum(1 for sr in staging if sr.get("write", "false") == "true")
    message = 0 if unit in ("FMA", "CVT", "SFU") else 1
    return (name, opcode[0], opcode[1], sources, dests, sr_read, sr_write, message)


def instructions(root):
    """Every instruction of the ISA, a group's members taking the group's operands."""
    rows = []
    for child in root:
        if child.tag == "ins":
            opcode = opcode_bits(child)
            if opcode is not None:
                rows.append(entry(child, child.get("name"), opcode, child.get("unit")))
        elif child.tag == "group":
            for ins in child.findall("ins"):
                opcode = opcode_bits(ins)
                if opcode is None:
                    continue
                unit = ins.get("unit") or child.get("unit")
                rows.append(entry(child, ins.get("name"), opcode, unit))
    return rows


def print_enums(root):
    """Prints each enum's values with the number each encodes as (reserved entries counted)."""
    for enum in root.findall("enum"):
        values = []
        index = 0
        for child in enum:
            if child.tag == "value":
                values.append("%d=%s" % (index, child.text))
                index += 1
            elif child.tag == "reserved":
                index += 1
        print("%s: %s" % (enum.get("name"), " ".join(values)))
    lut = root.find("lut")
    print("Immediates: %s" % " ".join("%d=%s" % (i, c.text) for i, c in enumerate(lut.findall("constant"))))


def main():
    root = ET.parse(sys.argv[1]).getroot()
    if sys.argv[2] == "--enums":
        print_enums(root)
        return
    rows = instructions(root)
    lines = []
    lines.append("/*")
    lines.append(" * Generated by the Mali compiler's ISA table tool from")
    lines.append(" * Mesa 26.2.6 src/panfrost/compiler/bifrost/valhall/ISA.xml (MIT): the")
    lines.append(" * Valhall instructions, their identifying opcode bits and their operands.")
    lines.append(" */")
    for name, mask, value, sources, dests, sr_read, sr_write, message in rows:
        flags = ", ".join("0x%02xU" % f for f, s in sources) or "0"
        sizes = ", ".join("%dU" % s for f, s in sources) or "0"
        lines.append("{ \"%s\", 0x%016xULL, 0x%016xULL, %dU, { %s }, { %s }, %dU, %dU, %dU, %dU },"
                     % (name, mask, value, len(sources), flags, sizes, dests, sr_read, sr_write, message))
    lut = root.find("lut")
    lines.append("#define ISA_TABLE_IMMEDIATES { %s }" % ", ".join(c.text + "U" for c in lut.findall("constant")))
    with open(sys.argv[2], "w") as out:
        out.write("\n".join(lines) + "\n")
    print("mali-compiler-isa-table: %d instructions" % len(rows))


main()
