#!/bin/sh
# Builds plan/ws039/tests/vkcompile.c into BUILD/bin/vkcompile: the pixel programs of plan/ws039/tests/vkcompile/
# compiled by glslc (-O, which inlines the functions the frontend does not call) into a header, then the same compile
# and link lines as the image's vkquad (the image's libvulkan.so and libc.so in BUILD/dynamic; the image is built
# first).
#   usage: plan/ws039/tests/vkcompile-build.sh BUILD   (for example build/p3/usb)
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
set -eu
BUILD=${1:?usage: vkcompile-build.sh BUILD}
TOP=$(pwd)
SYSROOT=$TOP/build/amd64/sysroot
CC=$TOP/build/llvm/bin/clang
OBJ=$BUILD/dynamic/obj/plan/ws039/tests
mkdir -p "$OBJ/vkcompile" "$BUILD/bin"

# The SPIR-V of each program as a C array vc_<name>_<stage>.
for source in plan/ws039/tests/vkcompile/*.vert plan/ws039/tests/vkcompile/*.frag; do
	name=$(basename "$source")
	glslc --target-env=vulkan1.0 -O -o "$OBJ/vkcompile/$name.spv" "$source"
done
python3 -I - "$OBJ/vkcompile" "$OBJ/vkcompile-shaders.h" <<'PYTHON'
import os, struct, sys
folder, header = sys.argv[1], sys.argv[2]
lines = ["/* Generated by plan/ws039/tests/vkcompile-build.sh. */", "#include <stdint.h>"]
for name in sorted(os.listdir(folder)):
    if not name.endswith(".spv"):
        continue
    data = open(os.path.join(folder, name), "rb").read()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    symbol = "vc_" + name[:-4].replace(".", "_")
    lines.append("static const uint32_t %s[] = {" % symbol)
    for start in range(0, len(words), 8):
        lines.append("\t" + ", ".join("0x%08xU" % word for word in words[start:start + 8]) + ",")
    lines.append("};")
open(header, "w").write("\n".join(lines) + "\n")
PYTHON

"$CC" --target=x86_64-unknown-zedbsd --sysroot="$SYSROOT" -nostdinc -I. -Iinclude -I"$OBJ" -isystem "$SYSROOT/usr/include" \
	-DHAL_ARCH_AMD64 -DKERN_USER_ABI_LP64 -DKERN_DYNAMIC_LIBC -m64 -march=x86-64 -mno-red-zone -Os -ffreestanding -fPIC \
	-fno-builtin -fno-stack-protector -fasynchronous-unwind-tables -ftls-model=global-dynamic -Wall -Wextra -Werror \
	-c plan/ws039/tests/vkcompile.c -o "$OBJ/vkcompile.o"
"$CC" --target=x86_64-unknown-zedbsd --sysroot="$SYSROOT" -m64 -nostdlib -pie -Wl,--no-relax \
	-Wl,--hash-style=gnu,-z,now,-z,relro,-z,separate-code -Wl,-z,stack-size=0x100000,--allow-shlib-undefined \
	-Wl,--dynamic-linker=/lib/ld.so "$SYSROOT/usr/lib/crt1.o" "$OBJ/vkcompile.o" \
	-L"$BUILD/dynamic" -Wl,-rpath-link,"$BUILD/dynamic" -l:libvulkan.so -l:libc.so -o "$BUILD/bin/vkcompile"
python3 tools/build/check-dynamic-elf.py --machine amd64 --role application --needed libvulkan.so --needed libc.so "$BUILD/bin/vkcompile"
