#!/usr/bin/env python3
# ws236-p003: makes src/drivers/platform/rpi4/rpi4-mmal-probe-data.inc, the probe's streams and reference checksums.
# Stream A is ws083's pb-high-352-pyramid (High, B pyramid, 352x288), copied to plan/ws236/tests/.  Stream B is a
# 1920x1080 High stream with B frames that this script encodes from ffmpeg's synthetic testsrc2 (kept as
# plan/ws236/tests/pb-high-1080.h264).  For each stream ffmpeg decodes the reference frames in display order; the
# checksum of a frame is FNV-1a 32 over its visible NV12 bytes (luma rows, then interleaved chroma rows); the decode
# order is the frames' order in the bitstream (ffprobe's pkt_pos).
# usage: python3 plan/ws236/tests/make-probe-data.py
# Copyright (C) 2026 Awe Morris; SPDX-License-Identifier: Zlib
import os, subprocess, sys
repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
tests = os.path.join(repo, 'plan', 'ws236', 'tests')
out_path = os.path.join(repo, 'src', 'drivers', 'platform', 'rpi4', 'rpi4-mmal-probe-data.inc')

def fnv(data):
    h = 0x811c9dc5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xffffffff
    return h

def stream_info(path):
    dims = subprocess.check_output(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries',
                                    'stream=width,height', '-of', 'csv=p=0', path]).decode().strip().split(',')
    w, h = int(dims[0]), int(dims[1])
    raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', path, '-f', 'rawvideo', '-pix_fmt', 'nv12', '-'])
    size = w * h * 3 // 2
    frames = [raw[i:i + size] for i in range(0, len(raw), size)]
    sums = [fnv(f) for f in frames]
    pos = subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'frame=pkt_pos', '-of', 'csv=p=0',
                                   path]).decode().split()
    pos = [int(p.strip(',')) for p in pos]
    if len(pos) != len(sums):
        sys.exit('frame count mismatch for ' + path)
    decode = sorted(range(len(pos)), key=lambda i: pos[i])
    return w, h, sums, decode

big = os.path.join(tests, 'pb-high-1080.h264')
if not os.path.exists(big) or os.path.getsize(big) < 1024:
    subprocess.check_call(['ffmpeg', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=1920x1080:rate=30',
                           '-frames:v', '8', '-c:v', 'libx264', '-profile:v', 'high', '-level', '4.1',
                           '-bf', '2', '-b_strategy', '0', '-g', '8', '-crf', '38',
                           '-f', 'h264', big])

lines = ['/*', ' * Generated by plan/ws236/tests/make-probe-data.py; do not edit.', ' *',
         ' * The probe\'s streams (pb-high-352-pyramid, ws083\'s test stream, and pb-high-1080,',
         ' * encoded from ffmpeg\'s synthetic testsrc2), the FNV-1a checksums of their',
         ' * reference frames in display order, and the display index of each frame',
         ' * in decode order.', ' */', '']
for name, path in (('small', os.path.join(tests, 'pb-high-352-pyramid.h264')), ('large', big)):
    data = open(path, 'rb').read()
    w, h, sums, decode = stream_info(path)
    lines.append('static const uint8_t probe_%s_stream[] = {' % name)
    for i in range(0, len(data), 16):
        lines.append('\t' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    lines.append('static const uint32_t probe_%s_width = %dU;' % (name, w))
    lines.append('static const uint32_t probe_%s_height = %dU;' % (name, h))
    lines.append('static const uint32_t probe_%s_display_sums[] = {' % name)
    lines.append('\t' + ', '.join('0x%08xU' % s for s in sums))
    lines.append('};')
    lines.append('static const uint8_t probe_%s_decode_order[] = {' % name)
    lines.append('\t' + ', '.join('%dU' % d for d in decode))
    lines.append('};')
    lines.append('')
    print('%s: %dx%d %d frames %d bytes decode order %s' % (name, w, h, len(sums), len(data), decode))
open(out_path, 'w').write('\n'.join(lines))
