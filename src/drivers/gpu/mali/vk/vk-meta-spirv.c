/*
 * The blit: one thread a target texel, eight by eight texels of one
 * layer a workgroup.  The source and the target are the images' linear
 * memory read as words (four bytes a texel), from the first layer of
 * each (the target from the region's first texel); the push constants
 * say the source region's corner (x, y), the steps through the source
 * for one target texel in 16.16 fixed point (negative for a flip), the
 * region's width and height in the target, the pitches and the layers'
 * sizes in words, the source's extent (texels are clamped to it) and the
 * flags (MALI_META_BLIT_LINEAR, MALI_META_BLIT_SWAP_RB).  A nearest blit
 * reads the texel under the target texel's centre; a linear one weighs
 * the four around it in 1/256ths, each byte on its own.  No division
 * and no float: the driver gives the steps.  Its source (blit.comp):
 *
 *	#version 450
 *	layout(local_size_x = 8, local_size_y = 8, local_size_z = 1) in;
 *	layout(set = 0, binding = 0) readonly buffer Source { uint texels[]; } source;
 *	layout(set = 0, binding = 1) writeonly buffer Target { uint texels[]; } target;
 *	layout(push_constant) uniform Blit {
 *		int x;
 *		int y;
 *		int step_x;
 *		int step_y;
 *		uint width;
 *		uint height;
 *		uint source_pitch;
 *		uint target_pitch;
 *		uint source_layer;
 *		uint target_layer;
 *		int source_width;
 *		int source_height;
 *		uint flags;
 *	} blit;
 *	void main()
 *	{
 *		uint tx = gl_GlobalInvocationID.x;
 *		uint ty = gl_GlobalInvocationID.y;
 *		uint layer = gl_WorkGroupID.z;
 *		if (tx < blit.width && ty < blit.height) {
 *			bool linear = (blit.flags & 1u) != 0u;
 *			int half_texel = linear ? 32768 : 0;
 *			uint weight_mask = linear ? 255u : 0u;
 *			int u = blit.step_x * int(tx) + blit.step_x / 2 - half_texel;
 *			int v = blit.step_y * int(ty) + blit.step_y / 2 - half_texel;
 *			int x0 = clamp(blit.x + (u >> 16), 0, blit.source_width - 1);
 *			int y0 = clamp(blit.y + (v >> 16), 0, blit.source_height - 1);
 *			int x1 = clamp(blit.x + (u >> 16) + 1, 0, blit.source_width - 1);
 *			int y1 = clamp(blit.y + (v >> 16) + 1, 0, blit.source_height - 1);
 *			uint fx = uint(u >> 8) & weight_mask;
 *			uint fy = uint(v >> 8) & weight_mask;
 *			uint base = layer * blit.source_layer;
 *			uint row0 = base + uint(y0) * blit.source_pitch;
 *			uint row1 = base + uint(y1) * blit.source_pitch;
 *			uint a = source.texels[row0 + uint(x0)];
 *			uint b = source.texels[row0 + uint(x1)];
 *			uint c = source.texels[row1 + uint(x0)];
 *			uint d = source.texels[row1 + uint(x1)];
 *			uint top_low = ((a & 0x00ff00ffu) * (256u - fx) + (b & 0x00ff00ffu) * fx + 0x00800080u) >> 8;
 *			uint top_high = (((a >> 8) & 0x00ff00ffu) * (256u - fx) + ((b >> 8) & 0x00ff00ffu) * fx + 0x00800080u) >> 8;
 *			uint bottom_low = ((c & 0x00ff00ffu) * (256u - fx) + (d & 0x00ff00ffu) * fx + 0x00800080u) >> 8;
 *			uint bottom_high = (((c >> 8) & 0x00ff00ffu) * (256u - fx) + ((d >> 8) & 0x00ff00ffu) * fx + 0x00800080u) >> 8;
 *			uint low = ((top_low & 0x00ff00ffu) * (256u - fy) + (bottom_low & 0x00ff00ffu) * fy + 0x00800080u) >> 8;
 *			uint high = ((top_high & 0x00ff00ffu) * (256u - fy) + (bottom_high & 0x00ff00ffu) * fy + 0x00800080u) >> 8;
 *			uint texel = (low & 0x00ff00ffu) | ((high & 0x00ff00ffu) << 8);
 *			if ((blit.flags & 2u) != 0u)
 *				texel = (texel & 0xff00ff00u) | ((texel >> 16) & 0xffu) | ((texel & 0xffu) << 16);
 *			target.texels[layer * blit.target_layer + ty * blit.target_pitch + tx] = texel;
 *		}
 *	}
 */
