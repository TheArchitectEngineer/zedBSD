/* The aspect copy's count of words. */
const size_t mali_meta_aspect_words = sizeof(mali_meta_aspect_spirv) / sizeof(mali_meta_aspect_spirv[0]);

/*
 * Copies the clear's fragment module with its colour at a location: the
 * literal of its one OpDecorate ... Location (the output's) changed.
 *
 * Values referenced: the SPIR-V specification 1.0 (OpDecorate 71,
 * Decoration Location 30, the word count in an instruction's high half).
 */
int
mali_meta_clear_color_at(
	uint32_t *words,
	size_t count,
	uint32_t location)
{
	size_t index;
	size_t length;
	size_t found;

	/* Room for the module. */
	if (count < mali_meta_clear_color_words)
		return -1;

	/* The module's words. */
	for (index = 0; index < mali_meta_clear_color_words; index++)
		words[index] = mali_meta_clear_color_spirv[index];

	/* Each instruction after the header, for the Location decorations. */
	found = 0;
	index = SPIRV_HEADER_WORDS;
	while (index < mali_meta_clear_color_words) {
		/* An instruction inside the module. */
		length = words[index] >> 16;
		if (length == 0U)
			return -1;
		if (index + length > mali_meta_clear_color_words)
			return -1;

		/* A Location decoration: its literal is the location. */
		if ((words[index] & 0xffffU) == SPIRV_OP_DECORATE && length == 4U) {
			if (words[index + 2U] == SPIRV_LOCATION) {
				words[index + 3U] = location;
				found++;
			}
		}

		index += length;
	}

	/* The one output, moved. */
	if (found != 1U)
		return -1;

	/* Succeeded: the module writes the location. */
	return 0;
}

/*
 * Converts a float's bits to an unsigned normalized value of a maximum
 * (65535 for 16 bits, 16777215 for 24), rounded to nearest, without
 * floating-point instructions: the value clamped to [0, 1] first, zero
 * for a NaN.
 *
 * Procedure referenced: the Vulkan specification 1.0 (the conversion of
 * a float to a normalized fixed-point value: the value clamped, times
 * 2^b - 1, rounded to nearest).
 */
uint32_t
mali_meta_unorm(
	uint32_t bits,
	uint32_t maximum)
{
	uint64_t product;
	uint32_t exponent;
	uint32_t shift;

	/* A negative value, a NaN, zero or a denormal: zero. */
	exponent = (bits >> 23) & 0xffU;
	if ((bits & 0x80000000U) != 0U || exponent == 0U)
		return 0;
	if (exponent == 0xffU && (bits & 0x7fffffU) != 0U)
		return 0;

	/* One and more: the maximum. */
	if (exponent >= 127U)
		return maximum;

	/* (1.m * 2^(e - 127)) * maximum, rounded at the last bit shifted out. */
	product = (uint64_t)((bits & 0x7fffffU) | 0x800000U) * maximum;
	shift = 23U + (127U - exponent);
	if (shift >= 63U)
		return 0;

	/* Succeeded: the normalized value. */
	return (uint32_t)((product + (1ULL << (shift - 1U))) >> shift);
}
