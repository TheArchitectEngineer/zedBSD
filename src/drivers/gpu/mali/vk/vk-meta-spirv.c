/*
 * The SPIR-V of the executor's own programs.  See vk-meta-spirv.h.
 *
 * Each module's words are the file that glslc (shaderc 2025.2) makes of
 * the source in the comment above it with
 * "glslc --target-env=vulkan1.0 -o <file> <source>" (the stage from the
 * source's extension: .comp, .vert, .frag), in order, as
 * "od -An -tx4 -v <file>" prints them on a little-endian host.
 */

