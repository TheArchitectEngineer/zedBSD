/*
 * Values referenced: Linux v6.19 drivers/gpu/drm/i915/gt/intel_lrc.c (NOP,
 * LRI, POSTED, REG, REG16, END: the encoding of the offset tables).
 */
#define I915_LRC_NOP(x) (I915_INC_BIT(7) | (x))
#define I915_LRC_LRI(count, flags) ((flags) << 6 | (count))
#define I915_LRC_POSTED I915_INC_BIT(0)
#define I915_LRC_REG(x) (((x) >> 2))
#define I915_LRC_REG16(x) \
	(((x) >> 9) | I915_INC_BIT(7)), \
	(((x) >> 2) & 0x7f)
#define I915_LRC_END 0

